def test_published_pages_name_a_commit_on_a_clean_tree():
    """On a committed tree (a CI checkout), docs/validation.md and docs/evaluation.md name
    the commit their runs were made from, never `<sha>-dirty`, which no commit reproduces
    (the Part 3 page was re-baselined in commit 18c6cc6; Part 4: `tasks.py rebaseline`).
    Skipped while the tree has uncommitted changes, when no run can name a commit yet."""
    spec = importlib.util.spec_from_file_location("tasks", ROOT / "tasks.py")
    tasks = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tasks)
    try:
        _, dirty = tasks.git_head()
    except SystemExit:
        pytest.skip("git is not available")
    if dirty:
        pytest.skip("uncommitted tree: the runs cannot name a commit yet")
    for doc in tasks.PUBLISHED_DOCS:
        page = (ROOT / doc).read_text(encoding="utf-8")
        assert "-dirty" not in page, f"{doc} names an uncommitted tree: run `tasks.py rebaseline`"


