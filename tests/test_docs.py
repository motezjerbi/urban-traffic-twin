def test_readme_part4_results_come_with_the_evaluation_page():
    """Either the Part 4 section still says its results are pending and no evaluation page
    exists, or it links the generated docs/evaluation.md, which reports A-04 and A-05."""
    part4 = flat(section(README, PART4))
    if part4.startswith(f"**{RESULTS_PENDING}**"):
        assert not EVALUATION_DOC.exists(), (
            "docs/evaluation.md exists: replace the 'Results pending' note of the README "
            "Part 4 section with the results"
        )
        return
    assert RESULTS_PENDING not in part4
    assert EVALUATION_DOC.is_file(), "README reports Part 4 results without docs/evaluation.md"
    assert "](docs/evaluation.md)" in part4, "Part 4 section does not link docs/evaluation.md"
    page = EVALUATION_DOC.read_text(encoding="utf-8")
    for needed in ("A-03", "A-04", "A-05"):
        assert needed in page, f"docs/evaluation.md: no {needed}"


def stated(pattern: str, text: str) -> tuple[str, ...]:
    m = re.search(pattern, text)
    assert m, f"README Part 4 section no longer matches {pattern!r}"
    return m.groups()


def num(x: str) -> float:
    return float(x)


def test_readme_part4_numbers_match_the_s2_config(rules_scenario):
    """The S2 parameters stated in the README Part 4 section are those of
    configs/pitie_rules.yaml (D23, D24, D36: derived from config, never hand-copied)."""
    text = flat(section(README, PART4))
    cfg, rules = rules_scenario, rules_scenario["rules"]
    safety = cfg["safety"]
    max_green, tsp = rules["max_green_s"], rules["tsp"]

    (theta,) = stated(r"θ = (\d+(?:\.\d+)?) s", text)
    assert num(theta) == safety["ped_max_wait_s"] - safety["ped_red_margin_s"]
    (wait, margin) = stated(r"`ped_max_wait_s` (\d+) minus `ped_red_margin_s` (\d+)", text)
    assert (num(wait), num(margin)) == (safety["ped_max_wait_s"], safety["ped_red_margin_s"])
    (min_green,) = stated(r"min green \((\d+) s\)", text)
    assert num(min_green) == safety["min_green_s"]

    (gap, s2_min) = stated(r"max-gap (\d+(?:\.\d+)?) s, min greens (\d+) s", text)
    assert num(gap) == rules["max_gap_s"] and {num(s2_min)} == set(rules["min_green_s"].values())
    hop, stm, other = stated(
        r"S2 max greens: HOP (\d+) s, STM (\d+) s, (\d+) s for the other stages", text
    )
    assert (num(hop), num(stm)) == (max_green["HOP"], max_green["STM"])
    others = {v for k, v in max_green.items() if k not in ("HOP", "STM")}
    assert others == {num(other)}
    (max_red,) = stated(r"`safety.max_red_s` is (\d+) s in S2", text)
    assert num(max_red) == safety["max_red_s"]

    assert set(stated(r"the green of (\w+), (\w+) or (\w+) is extended", text)) == set(
        tsp["extend_stages"]
    )
    (ext,) = stated(r"extended by up to (\d+(?:\.\d+)?) s", text)
    assert num(ext) == tsp["extension_max_s"]
    assert set(stated(r"lines (\d+), (\d+) or (\d+)", text)) == set(map(str, tsp["lines"]))
    speed, penalty = stated(r"distance at (\d+(?:\.\d+)?) m/s.* plus (\d+) s when stopped", text)
    assert (num(speed), num(penalty)) == (tsp["approach_speed_mps"], tsp["start_penalty_s"])
    assert not tsp["truncation"]["enabled"] and "(paid truncation) is off" in text
    cap = tsp["truncation"]["max_green_s"]
    trunc_hop, trunc_stm = stated(r"penalty cap \(HOP (\d+) s, STM (\d+) s\)", text)
    assert (num(trunc_hop), num(trunc_stm)) == (cap["HOP"], cap["STM"])

    (hold,) = stated(r"dropped after (\d+) s", text)
    assert cfg["preemption"]["enabled"] and num(hold) == cfg["preemption"]["max_hold_s"]


def test_readme_counts_the_dated_changes_of_the_evaluation():
    """The README Part 4 section states how many dated `changes` configs/evaluation.yaml
    has had since its pre-registration, and A-04 is worded on the curb wait it judges."""
    import yaml

    ecfg = yaml.safe_load((ROOT / "configs" / "evaluation.yaml").read_text(encoding="utf-8"))
    text = flat(section(README, PART4))
    (n,) = stated(r"\((\d+) dated changes? since, recorded in", text)
    assert int(n) == len(ecfg["changes"] or [])
    assert ecfg["a04"]["ped_curb_wait_max_s"] == "safety.ped_max_wait_s"
    assert "the longest pedestrian curb wait (`ped_curb_wait_max`)" in text


def test_readme_part4_tasks_exist():
    """Every task of the README Part 4 table is a tasks.py task, and the `part4` row lists
    the chain's steps in order."""
    spec = importlib.util.spec_from_file_location("tasks", ROOT / "tasks.py")
    tasks = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tasks)
    rows = re.findall(r"^\| `([^`]+)` \| (.*) \|$", section(README, "### Part 4 tasks"), re.M)
    names = [cmd.split()[0] for cmd, _ in rows]
    assert names and set(names) <= set(tasks.TASKS)
    assert {"evaluate", "plots-eval", "part4"} <= set(names)
    (part4_row,) = [what for cmd, what in rows if cmd == "part4"]
    assert f"`{' '.join(tasks.PART4_STEPS)}`" in part4_row
    assert f"`{tasks.PITIE_S2}`" in part4_row
    (rebaseline_row,) = [what for cmd, what in rows if cmd == "rebaseline"]
    assert f"`{' '.join(tasks.REBASELINE_STEPS)}`" in rebaseline_row
    assert "provenance" in names


def test_published_pages_name_a_commit_on_a_clean_tree():
    """On a committed tree (a CI checkout), docs/validation.md and docs/evaluation.md name
    the commit their runs were made from, never `<sha>-dirty`, which no commit reproduces
    (the Part 3 page was re-baselined in commit 18c6cc6; Part 4: `tasks.py rebaseline`).
    Skipped while the tree has uncommitted changes, when no run can name a commit yet."""
    spec = importlib.util.spec_from_file_location("tasks", ROOT / "tasks.py")
    tasks = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(tasks)
    try:
        _, dirty = tasks.git_head()
    except SystemExit:
        pytest.skip("git is not available")
    if dirty:
        pytest.skip("uncommitted tree: the runs cannot name a commit yet")
    for doc in tasks.PUBLISHED_DOCS:
        page = (ROOT / doc).read_text(encoding="utf-8")
        assert "-dirty" not in page, f"{doc} names an uncommitted tree: run `tasks.py rebaseline`"
