def stated(pattern: str, text: str) -> tuple[str, ...]:
    m = re.search(pattern, text)
    assert m, f"README section no longer matches {pattern!r}"
    return m.groups()


def num(x: str) -> float:
    return float(x)


def test_readme_part4_numbers_match_the_s2_config(rules_scenario):
    """The S2 parameters stated in the README Part 4 section are those of
    configs/pitie_rules.yaml (D23, D24, D36: derived from config, never hand-copied)."""
    text = flat(section(README, PART4))
    cfg, rules = rules_scenario, rules_scenario["rules"]
    safety = cfg["safety"]
    max_green, tsp = rules["max_green_s"], rules["tsp"]

    (theta,) = stated(r"θ = (\d+(?:\.\d+)?) s", text)
    assert num(theta) == safety["ped_max_wait_s"] - safety["ped_red_margin_s"]
    (wait, margin) = stated(r"`ped_max_wait_s` (\d+) minus `ped_red_margin_s` (\d+)", text)
    assert (num(wait), num(margin)) == (safety["ped_max_wait_s"], safety["ped_red_margin_s"])
    (min_green,) = stated(r"min green \((\d+) s\)", text)
    assert num(min_green) == safety["min_green_s"]

    (gap, s2_min) = stated(r"max-gap (\d+(?:\.\d+)?) s, min greens (\d+) s", text)
    assert num(gap) == rules["max_gap_s"] and {num(s2_min)} == set(rules["min_green_s"].values())
    hop, stm, other = stated(
        r"S2 max greens: HOP (\d+) s, STM (\d+) s, (\d+) s for the other stages", text
    )
    assert (num(hop), num(stm)) == (max_green["HOP"], max_green["STM"])
    others = {v for k, v in max_green.items() if k not in ("HOP", "STM")}
    assert others == {num(other)}
    (max_red,) = stated(r"`safety.max_red_s` is (\d+) s in S2", text)
    assert num(max_red) == safety["max_red_s"]

    assert set(stated(r"the green of (\w+), (\w+) or (\w+) is extended", text)) == set(
        tsp["extend_stages"]
    )
    (ext,) = stated(r"extended by up to (\d+(?:\.\d+)?) s", text)
    assert num(ext) == tsp["extension_max_s"]
    assert set(stated(r"lines (\d+), (\d+) or (\d+)", text)) == set(map(str, tsp["lines"]))
    speed, penalty = stated(r"distance at (\d+(?:\.\d+)?) m/s.* plus (\d+) s when stopped", text)
    assert (num(speed), num(penalty)) == (tsp["approach_speed_mps"], tsp["start_penalty_s"])
    assert not tsp["truncation"]["enabled"] and "(paid truncation) is off" in text
    cap = tsp["truncation"]["max_green_s"]
    trunc_hop, trunc_stm = stated(r"penalty cap \(HOP (\d+) s, STM (\d+) s\)", text)
    assert (num(trunc_hop), num(trunc_stm)) == (cap["HOP"], cap["STM"])

    (hold,) = stated(r"dropped after (\d+) s", text)
    assert cfg["preemption"]["enabled"] and num(hold) == cfg["preemption"]["max_hold_s"]


