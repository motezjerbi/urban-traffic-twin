def roadmap_rows() -> dict[str, tuple[str, str]]:
    """Part number (e.g. "5") -> (content, status) of the README roadmap table."""
    rows = re.findall(r"^\| (\d+(?:-\d+)?) \| (.*?) \|(.*)\|$", section(README, "## Roadmap"), re.M)
