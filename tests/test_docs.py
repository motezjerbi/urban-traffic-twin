def test_readme_part7_sensitivity_stress_and_verdict_match_the_rl7_config():
    """The sensitivity design, the stress panel, the interim 10.6 criteria and the
    compute plan stated in the README are those of configs/rl7.yaml (D76, D78, D79, D84)."""
    protocol = rl7_raw()["protocol"]
    text = flat(section(README, PART7))
    sens = protocol["sensitivity"]
    settings, steps = stated(r"the sensitivity settings (.*?), (\d+) decision steps each", text)
    assert backticked(settings) == sens["settings"] and int(steps) == sens["steps"]
    assert f"Around the `{sens['base']}` weights" in text
    wide_lo, wide_hi, def_lo, def_hi = stated(
        r"Seeds (\d+)-(\d+) for the base and the bus axis, (\d+)-(\d+) elsewhere", text
    )
    assert seed_list((wide_lo, wide_hi)) == sens["seeds_wide"]
    assert seed_list((def_lo, def_hi)) == sens["seeds_default"]
    assert set(sens["wide"]) == {sens["base"], "wb12", "wb50"}  # the base and the bus axis
    (n_boot,) = stated(r"hierarchical bootstrap \((\d+) resamples\)", text)
    assert int(n_boot) == sens["bootstrap"]["n"]

    stress = protocol["stress"]
    (n_cells,) = stated(r"S3, S0, S1 and S2 on (\d+) stress cells", text)
    assert int(n_cells) == len(stress["cells"])
    (worse,) = stated(r"S3 is more than (\d+) % worse than S1 is named", text)
    assert num(worse) / 100 == stress["worse_than_s1_rel"]

    gate, devtest = protocol["gate_10_6"], protocol["devtest"]
    assert devtest["primary"] == "all/person_delay_mean" and "person-weighted delay" in text
    (alpha,) = stated(r"exact Wilcoxon p below (0\.\d+)", text)
    assert num(alpha) == devtest["alpha"]
    (equity,) = stated(r"pedestrian mean curb wait are not more than (\d+) % worse than S1", text)
    assert num(equity) / 100 == gate["equity_rel"]
    assert gate["equity_kpis"] == [
        "car/time_loss_mean", "bus/delay_mean", "pedestrian/ped_curb_wait_mean",
    ]  # fmt: skip
    (curb,) = stated(r"every curb wait at or under (\d+) s", text)
    assert int(curb) == gate["curb_max_s"]
    runs, of = stated(r"at least (\d+) of the (\d+) stage-F picks beat S1", text)
    assert (int(runs), int(of)) == (gate["repro_min_runs"], len(protocol["stage_f"]["seeds"]))

