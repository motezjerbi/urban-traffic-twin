    total, t_runs, s_runs, f_runs = stated(
        r"(\d+) trainings in all \(stage T (\d+), sensitivity (\d+), stage F (\d+)\)", text
    )
    assert (int(t_runs), int(s_runs), int(f_runs)) == (n_t, n_s, len(f["seeds"]))
    assert int(total) == n_t + n_s + len(f["seeds"])
    (s_new,) = stated(r"elsewhere: (\d+) new runs", text)
    assert int(s_new) == n_s
    (slots,) = stated(r"(\d+) trainings at once \(`protocol\.slots`", text)
    assert int(slots) == protocol["slots"]


